/**
 * Generate stable relay tool schemas from the actual compiled agent dispatcher.
 * Clients often cache tools/list on first connection, so don't derive the public
 * schema solely from whichever agent sockets happen to be online at that moment.
 * Run after pnpm --filter brc-agent build; --check verifies the committed snapshot.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { listTools } from '../packages/agent/dist/dispatcher.js';

const target = fileURLToPath(new URL('../packages/relay/src/mcp/agent-tools.catalog.ts', import.meta.url));
delete process.env.BRC_TOOL_PROFILE;
// The agent's upstream descriptions include machine-specific shell and Docker path
// guidance. Keep bundled relay schemas OS-neutral so Windows/Linux CI and
// hosted builds generate the exact same snapshot.
function portableDescription(name, original) {
  let description = original;
  const pathLead = 'IMPORTANT: Always use absolute paths for reliability.';
  const pathTail = 'Unless the user explicitly asks for relative paths, use absolute paths.';
  let start;
  while ((start = description.indexOf(pathLead)) !== -1) {
    const end = description.indexOf(pathTail, start);
    if (end < 0) throw new Error('Unexpected platform-specific path guidance for ' + name);
    description = description.slice(0, start)
      + 'IMPORTANT: Use absolute paths appropriate for the connected device. Relative paths may depend on the active shell and working directory.'
      + description.slice(end + pathTail.length);
  }
  if (name === 'start_process') {
    const left = 'CRITICAL RULE: For ANY local file work, ALWAYS use this tool + interact_with_process, NEVER use analysis/REPL tool.';
    const right = 'REQUIRED WORKFLOW FOR LOCAL FILES:';
    const from = description.indexOf(left);
    const to = description.indexOf(right, from + left.length);
    if (from < 0 || to < 0) throw new Error('Unexpected start_process tool description format');
    description = description.slice(0, from + left.length)
      + '\n\n                Commands run on the connected device. Check its actual operating system and shell (Windows, Linux, macOS) before choosing shell syntax.\n\n                '
      + description.slice(to);
  }
  return description;
}
const definitions = listTools().map(({ name, description, inputSchema, annotations }) =>
  ({ name, description: portableDescription(name, description), inputSchema, ...(annotations ? { annotations } : {}) }));
const names = new Set(definitions.map(tool => tool.name));
if (definitions.length < 20 || names.size !== definitions.length)
  throw new Error('Refusing to generate incomplete or duplicate tool definitions');
const body = JSON.stringify(definitions, null, 2);
const source = [
  '// Generated by scripts/generate-relay-catalog.mjs. Do not edit manually.',
  '// Stable MCP schema even when an agent is offline or reconnecting.',
  "import type { ToolDefinition } from 'brc-shared';",
  `export const BUNDLED_AGENT_TOOL_CATALOG: ToolDefinition[] = ${body};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  try {
    if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) throw new Error('out of date');
  } catch {
    console.error('Bundled tool catalog is out of date. Run pnpm catalog:update after building the agent.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, source, 'utf8');
}
console.log(`${definitions.length} bundled tools (${Buffer.byteLength(source)} bytes), ${process.argv.includes('--check') ? 'checked' : 'generated'}`);
