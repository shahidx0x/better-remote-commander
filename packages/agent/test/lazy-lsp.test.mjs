import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {mkdtempSync,realpathSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const fixture=fileURLToPath(new URL('./fixtures/fake-lsp-server.mjs',import.meta.url));
const tmp=mkdtempSync(path.join(realpathSync.native(os.tmpdir()),'brc-lazy-lsp-'));
const root=path.join(tmp,'root');
process.env.BRC_HOME=path.join(tmp,'home');
await fs.mkdir(root,{recursive:true});
await fs.writeFile(path.join(root,'main.rs'),'fn hello() {}\n');
await fs.writeFile(path.join(root,'main.cs'),'class Hello {}\n');
await fs.writeFile(path.join(root,'main.py'),'def hello(): pass\n');
const {configManager}=await import('../dist/core/config-manager.js');
await configManager.setValue('allowedDirectories',[root]);
const {LazyLanguageServer,lazyLanguageServer}=await import('../dist/runtime/lazy-lsp.js');
const {callTool}=await import('../dist/dispatcher.js');
const {sha256}=await import('../dist/runtime/file-safety.js');
const clients=[];
const create=()=>{const m=new LazyLanguageServer(()=>({command:process.execPath,args:[fixture]}));clients.push(m);return m;};
after(async()=>{for(const m of clients)m.close();lazyLanguageServer.close();
 await configManager.close();await fs.rm(tmp,{recursive:true,force:true,maxRetries:8,retryDelay:100});});
test('public LSP status consumes no child RAM and reports native server availability',async()=>{
 const r=await callTool('lsp_query',{action:'status'});
 assert.notEqual(r.isError,true,JSON.stringify(r));
 assert.equal(r.structuredContent.active,false);
 assert.equal(r.structuredContent.maxProcesses,1);
 assert.equal(r.structuredContent.autoInstall,false);
});
test('lazy C#/Rust/Python servers start on first real semantic request, reuse, and release',async()=>{
 const lsp=create();assert.equal(lsp.status().launched,0);assert.equal(lsp.status().active,false);
 const first=await lsp.query({path:root,file:'main.rs',action:'definition',line:1,column:4});
 assert.equal(first.provider,'rust-analyzer');
 assert.equal(first.data.length,1);
 assert.equal(first.sourceSha256,sha256('fn hello() {}\n'));
 assert.equal(lsp.status().launched,1);
 const hover=await lsp.query({path:root,file:'main.rs',action:'hover',line:1,column:4});
 assert.match(hover.data.contents,/version 1/);
 assert.equal(lsp.status().launched,1,'reuse process for same project and language');
 await fs.writeFile(path.join(root,'main.rs'),'fn hello_again() {}\n');
 const updated=await lsp.query({path:root,file:'main.rs',action:'hover',line:1,column:4});
 assert.match(updated.data.contents,/version 2/);
 assert.equal(updated.sourceSha256,sha256('fn hello_again() {}\n'));
 await lsp.query({path:root,file:'main.cs',action:'document_symbols'});
 assert.equal(lsp.status().language,'csharp');
 await lsp.query({path:root,file:'main.py',action:'document_symbols'});
 assert.equal(lsp.status().language,'python');
 assert.equal(lsp.status().launched,3);
 lsp.close();assert.equal(lsp.status().active,false);
 assert.equal(lsp.status().closed,3);
});
test('unavailable language server and out-of-workspace requests fail closed without starting child',async()=>{
 const never=new LazyLanguageServer(()=>null);clients.push(never);
 await assert.rejects(never.query({path:root,file:'main.py',action:'hover',line:1,column:1}),e=>e.code==='LSP_SERVER_NOT_INSTALLED');
 assert.equal(never.status().launched,0);
 const lsp=create();
 await assert.rejects(lsp.query({path:root,file:'../outside.cs',action:'definition',line:1,column:1}),e=>e.code==='OUTSIDE_PROJECT');
 await assert.rejects(lsp.query({path:root,file:'main.rs',action:'hover',line:0,column:1}),e=>e.code==='LSP_POSITION_REQUIRED');
 assert.equal(lsp.status().launched,0);
});
