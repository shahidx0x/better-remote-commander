import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {mkdtempSync,realpathSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
const dir=mkdtempSync(path.join(realpathSync.native(os.tmpdir()),'brc-append-durable-'));
process.env.BRC_HOME=path.join(dir,'home');
const {configManager}=await import('../dist/core/config-manager.js');
await configManager.setValue('allowedDirectories',[dir]);
const {callTool}=await import('../dist/dispatcher.js');
const {sha256}=await import('../dist/runtime/file-safety.js');
const id=()=>randomUUID();
const target=n=>path.join(dir,n);
after(async()=>{await configManager.close();await fs.rm(dir,{force:true,recursive:true,maxRetries:6,retryDelay:60});});
test('same durable append ID cannot append twice, including after already-committed acknowledgement',async()=>{
 const file=target('existing.txt'),token=id();await fs.writeFile(file,'start\n');
 const originalHash=sha256('start\n');
 const args={path:file,content:'hello\n',mode:'append',append_id:token,expected_sha256:originalHash};
 const first=await callTool('write_file',args);
 assert.notEqual(first.isError,true,JSON.stringify(first));
 assert.equal(first.structuredContent.write.appendReceipt.alreadyApplied,false);
 assert.equal(await fs.readFile(file,'utf8'),'start\nhello\n');
 const retry=await callTool('write_file',args);
 assert.notEqual(retry.isError,true,JSON.stringify(retry));
 assert.equal(retry.structuredContent.write.appendReceipt.alreadyApplied,true);
 assert.equal(await fs.readFile(file,'utf8'),'start\nhello\n');
});
test('new file may be durably created once, while changing content under same ID fails',async()=>{
 const file=target('nested/new.txt'),token=id();
 const x=await callTool('write_file',{path:file,mode:'append',content:'chunk',append_id:token});
 assert.notEqual(x.isError,true,JSON.stringify(x));
 const y=await callTool('write_file',{path:file,mode:'append',content:'chunk',append_id:token});
 assert.equal(y.structuredContent.write.alreadyApplied,true);
 const incompatible=await callTool('write_file',{path:file,mode:'append',content:'NEW',append_id:token});
 assert.equal(incompatible.isError,true);
 assert.equal(incompatible.structuredContent.error.code,'APPEND_ID_REUSED');
 assert.equal(await fs.readFile(file,'utf8'),'chunk');
});
test('replay after third-party changes fails closed and retains original content',async()=>{
 const file=target('changed.txt'),token=id();
 await fs.writeFile(file,'base');
 const first=await callTool('write_file',{path:file,mode:'append',content:'A',append_id:token});
 assert.notEqual(first.isError,true);
 await fs.appendFile(file,'B');
 const retry=await callTool('write_file',{path:file,mode:'append',content:'A',append_id:token});
 assert.equal(retry.isError,true);
 assert.equal(retry.structuredContent.error.code,'APPEND_OUTCOME_UNCERTAIN');
 assert.equal(await fs.readFile(file,'utf8'),'baseAB');
});
test('retries on a simulated planned receipt reconcile without duplicate content',async()=>{
 const file=target('recovery.txt'),token=id();
 await fs.writeFile(file,'old');
 const first=await callTool('write_file',{path:file,mode:'append',content:'NEW',append_id:token});
 assert.notEqual(first.isError,true);
 const crypto=await import('node:crypto');
 const disk=path.join(process.env.BRC_HOME,'append-receipts',crypto.createHash('sha256').update(token).digest('hex')+'.json');
 const receipt=JSON.parse(await fs.readFile(disk,'utf8'));
 assert.equal(JSON.stringify(receipt).includes('NEW'),false,'metadata-only journal');
 await fs.writeFile(disk,JSON.stringify({...receipt,state:'planned'}));
 const recovered=await callTool('write_file',{path:file,mode:'append',content:'NEW',append_id:token});
 assert.notEqual(recovered.isError,true);
 assert.equal(recovered.structuredContent.write.alreadyApplied,true);
 assert.equal(await fs.readFile(file,'utf8'),'oldNEW');
});
test('ordinary legacy append still works unchanged without receipt',async()=>{
 const file=target('legacy.txt');await fs.writeFile(file,'A');
 const r=await callTool('write_file',{path:file,mode:'append',content:'B'});
 assert.notEqual(r.isError,true,JSON.stringify(r));assert.equal(await fs.readFile(file,'utf8'),'AB');
});
